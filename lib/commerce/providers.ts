import type { CommerceProvider } from "./types";

function storefront(
  id: string,
  name: string,
  countries: CountryCode[],
  categories: CommerceCategory[],
  url: string,
  description: string,
): CommerceProvider {
  return {
    id,
    name,
    countries,
    categories,
    url,
    sourceUrl: url,
    description,
    payment: "fiat",
    handoff: "storefront",
    caveat:
      "Complete checkout with the provider's supported payment methods. A NEAR-funded payment route is not connected. Delivery depends on your exact address.",
  };
}

